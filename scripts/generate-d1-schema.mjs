import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sourceUrl = new URL("../prisma/schema.prisma", import.meta.url);
const targetUrl = new URL("../prisma/schema.d1.prisma", import.meta.url);

const source = await readFile(sourceUrl, "utf8");

const replacements = [
  [
    'output   = "../generated/prisma"',
    'output   = "../generated/prisma-d1"\n  runtime  = "cloudflare"',
  ],
  ['provider = "postgresql"', 'provider = "sqlite"'],
];

let schema = source;
for (const [from, to] of replacements) {
  if (!schema.includes(from)) {
    throw new Error(`D1 schema generation could not find: ${from}`);
  }
  schema = schema.replace(from, to);
}

schema = schema.replaceAll(" @db.Date", "");
schema = `// Generated from prisma/schema.prisma by ${fileURLToPath(import.meta.url)}.\n// Do not edit this file directly.\n\n${schema}`;

await writeFile(targetUrl, schema);
